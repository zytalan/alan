// Writes src/ui/geo.ts for the birth lottery map: a land mask on a 2.4° grid, the Equal Earth
// projection parameters and a label point for every country in world.json.
// Source: Natural Earth 1:110m via world-atlas (public domain). Run with `npm run geo`.
import { readFileSync, writeFileSync } from "node:fs";
import { geoEqualEarth, geoContains, geoCentroid, geoArea } from "d3-geo";
import { feature } from "topojson-client";
const read = (path) => JSON.parse(readFileSync(new URL(path, import.meta.url), "utf8"));
const lt = read("../node_modules/world-atlas/land-110m.json");
const land = feature(lt, lt.objects.land);
const ct = read("../node_modules/world-atlas/countries-110m.json");
const countries = feature(ct, ct.objects.countries).features;
const num2iso = read("./iso-numeric.json"); // ISO 3166-1 numeric → alpha-3
const world = read("../public/data/world.json");
const W = 640, H = 312, step = 2.4, lat0 = 82, lon0 = -180, cols = Math.round(360 / step);
const proj = geoEqualEarth().fitExtent([[6, 6], [W - 6, H - 6]], { type: "Sphere" });
let bits = "", rows = 0;
for (let k = 0; ; k++) {
  const lat = lat0 - k * step;
  if (lat < -58) break;
  rows++;
  for (let i = 0; i < cols; i++) bits += geoContains(land, [lon0 + i * step, lat]) ? "1" : "0";
}
const bytes = new Uint8Array(Math.ceil(bits.length / 8));
for (let i = 0; i < bits.length; i++) if (bits[i] === "1") bytes[i >> 3] |= 128 >> (i & 7);
const cent = {};
for (const f of countries) {
  const iso = num2iso[String(f.id).padStart(3, "0")];
  if (!iso || !world.countries[iso]) continue;
  let g = f.geometry;
  if (g.type === "MultiPolygon") {
    let best = null, ba = -1;
    for (const p of g.coordinates) { const poly = { type: "Polygon", coordinates: p }; const a = geoArea(poly); if (a > ba) { ba = a; best = poly; } }
    g = best;
  }
  const [lon, lat] = geoCentroid({ type: "Feature", geometry: g });
  cent[iso] = [+lon.toFixed(1), +lat.toFixed(1)];
}
// small places the 1:110m map leaves out
Object.assign(cent, { BHR: [50.6, 26.0], COM: [43.9, -11.9], CPV: [-23.6, 15.1], HKG: [114.2, 22.3], MAC: [113.5, 22.2], MDV: [73.5, 4.2], MLT: [14.4, 35.9], MUS: [57.6, -20.3], SGP: [103.8, 1.35], XKX: [20.9, 42.6] });
const missing = Object.keys(world.countries).filter((k) => !cent[k]);
const body = `// Generated by a script from Natural Earth via world-atlas (public domain): a land mask on a
// ${step}° grid, Equal Earth projection parameters for a ${W}×${H} map, and a label point for each country.
/* eslint-disable */
export const MAP = {
  W: ${W},
  H: ${H},
  step: ${step},
  lat0: ${lat0},
  lon0: ${lon0},
  cols: ${cols},
  rows: ${rows},
  scale: ${proj.scale().toFixed(4)},
  translate: [${proj.translate().map((v) => v.toFixed(2)).join(", ")}] as [number, number],
  mask: "${Buffer.from(bytes).toString("base64")}",
};

export const CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(cent).replace(/"([A-Z]{3})":/g, "$1:").replace(/,(?=[A-Z]{3}:)/g, ", ")};
`;
writeFileSync(new URL("../src/ui/geo.ts", import.meta.url), body);
console.log("rows", rows, "cols", cols, "centroids", Object.keys(cent).length, "missing", missing.join(" ") || "none");
